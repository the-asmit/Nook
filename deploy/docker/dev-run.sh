#!/usr/bin/env bash
# dev-run.sh up|down: run the nook-server, nook-agent and nook-gateway
# images against the dev stack (`make docker-run` / `make docker-stop`).
#
# The containers get the settings from .env, rewritten for where they run:
#   nook-server   on the nook-dev network, reaching postgres, redis, minio
#                 and the registry by service name; API on
#                 127.0.0.1:$DOCKER_RUN_PORT, gRPC as nook-server:9443.
#   nook-gateway  on nook-dev at a fixed address ($GATEWAY_IP); apps on
#                 127.0.0.1:$GATEWAY_PORT, ops on 127.0.0.1:9102.
#   nook-agent    this machine's dev node (.nook-dev/agent), on nook-dev,
#                 managing containers through the Docker socket; health on
#                 127.0.0.1:9101. App ports accept only the gateway.
# Each container gets only its own settings, from an env file (mode 0600)
# in .nook-dev/docker/. All run as non-root users with a read-only root
# file system, no capabilities and no-new-privileges.
#
# Known limits of the containerized dev setup: browser sign-in needs Dex
# under the same name for the browser and the server (it is localhost:5556
# for the browser), so OIDC sign-in works with `make run-server` only; and
# builds need presigned storage URLs that both the CLI and the agent reach
# (one S3 host name in production), so build with `make run-agent`.
# On Docker Desktop, published ports are forwarded by Docker Desktop's own
# proxy inside its VM, which the agent's gateway-only firewall rule does
# not see: other containers can reach app ports through
# host.docker.internal there. On Linux the rule applies.
set -euo pipefail

cd "$(dirname "$0")/../.."
: "${IMAGE:?}" "${AGENT_IMAGE:?}" "${GATEWAY_IMAGE:?}" "${VERSION:?}" "${DOCKER_RUN_PORT:?}"
readonly BUSYBOX=busybox:1.37@sha256:a7dbc319b1438115a207e11930dc4bb3e643dcb3ec0bdd694bb36cd8fad289ec
readonly NETWORK=nook-dev GATEWAY_IP=172.31.250.200 LABEL=nook.dev-run=true
readonly ENV_DIR=.nook-dev/docker
readonly HARDENING=(--read-only --cap-drop=ALL --security-opt=no-new-privileges --tmpfs /tmp:rw,noexec,nosuid,size=64m)

die() { echo "dev-run: $*" >&2; exit 1; }

down() {
	local ids
	ids=$(docker ps -aq --filter "label=$LABEL")
	if [[ -n $ids ]]; then
		# shellcheck disable=SC2086 # one ID per word
		docker rm -f $ids >/dev/null
		echo "Removed the nook-server, nook-agent and nook-gateway containers."
	fi
}

# envfile NAME: writes stdin (KEY=VALUE lines) to $ENV_DIR/NAME.env, 0600.
envfile() {
	(umask 077 && cat >"$ENV_DIR/$1.env")
}

# pick PREFIX...: KEY=VALUE for every set variable starting with a prefix.
pick() {
	local name prefix
	for name in $(compgen -e | sort); do
		for prefix in "$@"; do
			if [[ $name == "$prefix"* ]]; then
				printf '%s=%s\n' "$name" "${!name}"
				break
			fi
		done
	done
}

# without NAME...: filters KEY=VALUE lines from stdin, dropping NAMEs.
without() {
	local pattern
	pattern="^($(IFS='|'; echo "$*"))="
	grep -Ev "$pattern" || true
}

# wait_ready NAME URL: polls URL until it answers 200 (90 s at most).
wait_ready() {
	local deadline=$((SECONDS + 90))
	until [[ $(curl -s -o /dev/null -w '%{http_code}' "$2" || true) == 200 ]]; do
		if ((SECONDS > deadline)); then
			docker logs --tail 30 "$1" >&2 || true
			die "$1 did not become ready at $2"
		fi
		sleep 1
	done
	echo "$1 is ready ($2)"
}

up() {
	[[ -f .env ]] || die "no .env; run make env"
	pgrep -x nook-agent >/dev/null && die "a nook-agent process is running (make run-agent); stop it first: the container runs the same node"
	pgrep -x nook-gateway >/dev/null && die "a nook-gateway process is running (make run-gateway); stop it first: the container needs its ports"
	local img
	for img in "$IMAGE:$VERSION" "$AGENT_IMAGE:$VERSION" "$GATEWAY_IMAGE:$VERSION"; do
		docker image inspect "$img" >/dev/null 2>&1 || die "image $img not found; run make docker-build (PLATFORMS=linux/$(go env GOARCH) for this machine only)"
	done
	[[ -d .nook-dev/agent ]] || die "no .nook-dev/agent; join this machine first (see README)"
	set -a
	# shellcheck disable=SC1091 # generated by make env
	source ./.env
	set +a

	# Where app ports are bound and reached. Docker Desktop publishes ports
	# on the host side only (nothing listens inside its VM, and bindings
	# on VM addresses are dropped): bind 127.0.0.1 and reach it through
	# host.docker.internal. Native Docker binds on the nook-dev bridge
	# address, which the gateway and the agent reach directly.
	local advertise publish=""
	if [[ $(docker info --format '{{.OperatingSystem}}') == "Docker Desktop" ]]; then
		advertise=$(docker run --rm "$BUSYBOX" nslookup -type=A host.docker.internal 2>/dev/null | awk '/^Address/ {a=$2} END {print a}')
		[[ -n $advertise ]] || die "cannot resolve host.docker.internal"
		publish=127.0.0.1
	else
		advertise=$(docker network inspect "$NETWORK" --format '{{(index .IPAM.Config 0).Gateway}}')
	fi
	local socket_gid
	socket_gid=$(docker run --rm -v /var/run/docker.sock:/var/run/docker.sock "$BUSYBOX" stat -c %g /var/run/docker.sock)

	mkdir -p "$ENV_DIR"
	chmod 700 "$ENV_DIR"
	local redis="redis://:${REDIS_PASSWORD}@redis:6379/0"
	{
		pick NOOK_ | without NOOK_AGENT_.* NOOK_GATEWAY_.* NOOK_HTTP_ADDR NOOK_PUBLIC_URL NOOK_POSTGRES_URL NOOK_REDIS_URL \
			NOOK_S3_ENDPOINT NOOK_S3_PRESIGN_ENDPOINT NOOK_REGISTRY_URL NOOK_GRPC_.* NOOK_PKI_CA_PATH NOOK_SECRETS_KEY_FILE \
			NOOK_HTTP_TLS_.*
		cat <<-EOF
			NOOK_GATEWAY_SECRET=$NOOK_GATEWAY_SECRET
			NOOK_HTTP_ADDR=:8080
			NOOK_PUBLIC_URL=http://localhost:$DOCKER_RUN_PORT
			NOOK_POSTGRES_URL=postgres://$POSTGRES_USER:$POSTGRES_PASSWORD@postgres:5432/$POSTGRES_DB?sslmode=disable
			NOOK_REDIS_URL=$redis
			NOOK_S3_ENDPOINT=http://minio:9000
			NOOK_S3_PRESIGN_ENDPOINT=${NOOK_S3_PRESIGN_ENDPOINT:-$NOOK_S3_ENDPOINT}
			NOOK_REGISTRY_URL=https://registry:5000
			NOOK_GRPC_ADDR=:9443
			NOOK_GRPC_PUBLIC_ADDR=nook-server:9443
			NOOK_GRPC_SERVER_NAMES=nook-server,localhost
			NOOK_PKI_CA_PATH=/nook/pki/ca.pem
			NOOK_SECRETS_KEY_FILE=/nook/secrets.key
		EOF
	} | envfile server
	{
		pick NOOK_ENV NOOK_LOG_ NOOK_REDIS_ NOOK_APPS_BASE_URL NOOK_GATEWAY_ | without NOOK_REDIS_URL NOOK_GATEWAY_CONTROL_PLANE_URL \
			NOOK_GATEWAY_TLS_MODE NOOK_GATEWAY_HTTP_ADDR NOOK_GATEWAY_OPS_ADDR
		cat <<-EOF
			NOOK_REDIS_URL=$redis
			NOOK_GATEWAY_CONTROL_PLANE_URL=http://nook-server:8080
			NOOK_GATEWAY_TLS_MODE=off
			NOOK_GATEWAY_HTTP_ADDR=:8080
			NOOK_GATEWAY_OPS_ADDR=:9102
		EOF
	} | envfile gateway
	{
		pick NOOK_LOG_ NOOK_AGENT_ | without NOOK_AGENT_STATE_DIR NOOK_AGENT_HEALTH_ADDR NOOK_AGENT_ADVERTISE_ADDR \
			NOOK_AGENT_PUBLISH_ADDR NOOK_AGENT_SERVER_ADDR NOOK_AGENT_REGISTRY_PULL_ADDR NOOK_AGENT_GATEWAY_ADDRS
		cat <<-EOF
			NOOK_AGENT_STATE_DIR=/var/lib/nook-agent
			NOOK_AGENT_HEALTH_ADDR=:9101
			NOOK_AGENT_SERVER_ADDR=nook-server:9443
			NOOK_AGENT_ADVERTISE_ADDR=$advertise
			NOOK_AGENT_GATEWAY_ADDRS=$GATEWAY_IP/32
		EOF
		[[ -z $publish ]] || echo "NOOK_AGENT_PUBLISH_ADDR=$publish"
	} | envfile agent

	down
	local user
	user="$(id -u):$(id -g)" # owns .nook-dev (keys are mode 0600)
	docker run -d --name nook-server --label "$LABEL" --network "$NETWORK" "${HARDENING[@]}" --user "$user" \
		--env-file "$ENV_DIR/server.env" --publish "127.0.0.1:$DOCKER_RUN_PORT:8080" \
		-v "$PWD/.nook-dev/pki:/nook/pki:ro" -v "$PWD/.nook-dev/secrets.key:/nook/secrets.key:ro" \
		"$IMAGE:$VERSION" >/dev/null
	wait_ready nook-server "http://127.0.0.1:$DOCKER_RUN_PORT/readyz"
	docker run -d --name nook-gateway --label "$LABEL" --network "$NETWORK" --ip "$GATEWAY_IP" "${HARDENING[@]}" \
		--env-file "$ENV_DIR/gateway.env" --publish "127.0.0.1:${GATEWAY_PORT:-8090}:8080" --publish 127.0.0.1:9102:9102 \
		"$GATEWAY_IMAGE:$VERSION" >/dev/null
	wait_ready nook-gateway http://127.0.0.1:9102/readyz
	# The Docker socket is root on the host: only for dedicated workers.
	docker run -d --name nook-agent --label "$LABEL" --network "$NETWORK" "${HARDENING[@]}" --user "$user" --group-add "$socket_gid" \
		--env-file "$ENV_DIR/agent.env" --publish 127.0.0.1:9101:9101 \
		-v /var/run/docker.sock:/var/run/docker.sock -v "$PWD/.nook-dev/agent:/var/lib/nook-agent" \
		"$AGENT_IMAGE:$VERSION" run >/dev/null
	wait_ready nook-agent http://127.0.0.1:9101/readyz
	cat <<-EOF
		API:  http://127.0.0.1:$DOCKER_RUN_PORT  (NOOK_SERVER=http://127.0.0.1:$DOCKER_RUN_PORT with your API token)
		Apps: ${NOOK_APPS_BASE_URL}  (app ports advertised at $advertise; redeploy apps placed before)
		Logs: docker logs -f nook-server | nook-gateway | nook-agent; stop with make docker-stop
	EOF
}

case "${1:-up}" in
up) up ;;
down) down ;;
*) die "usage: $0 up|down" ;;
esac
